/* =====================================================================
   PLAYING YOUR ANIMATIONS
   =====================================================================
   The pictures come from the build script (build_frames.py), which stacks
   your Procreate layers (background, base, frame, fg), crops them and saves
   one finished image per frame. This file only has to answer two questions:
     1. Which image should be showing right now?
     2. Draw it onto a canvas.
   Timing comes from ANIMS_RAW (4 fps): a list of [image number, milliseconds]. */

// Small shared helpers (also used by the floating-word code further down)
const TAU = Math.PI * 2;                 // a full circle in radians
const BG = '#192131';                    // the navy behind every picture
const ease = x => x < 0 ? 0 : x > 1 ? 1 : x * x * (3 - 2 * x);   // smooth start and stop, for 0..1
const c01 = x => x < 0 ? 0 : x > 1 ? 1 : x;                      // clamp a number to 0..1

// Load every frame image once, when the page opens
const IMGS = ANIM_FILES.map(f => { const im = new Image(); im.src = f; return im; });

// Turn each timing list into running totals, so we can look up a frame by time.
// Example: [[0,1000],[1,250]] becomes [{k:0,end:1000},{k:1,end:1250}] with total 1250.
const ANIM = {};
Object.entries(ANIMS_RAW).forEach(([name, seq]) => {
  let end = 0; const s = seq.map(([k, ms]) => ({ k, end: (end += ms) }));
  ANIM[name] = { seq: s, total: end };
});

// The animation that belongs to panel number i
const animOf = i => ANIM[PANELS[i].anim];

// Which image is showing `ms` milliseconds into the animation?
// The % (modulo) makes it loop forever: after the last frame it wraps back to the first.
function animIdx(A, ms) {
  const p = ((ms % A.total) + A.total) % A.total;
  for (const s of A.seq) if (p < s.end) return s.k;
  return A.seq[A.seq.length - 1].k;
}

// Draw panel i onto canvas context `c`.
//   size = canvas size in pixels, t = time in seconds,
//   mode = 0 (waiting for the drag: first frame, held still) or 1 (playing).
// Everything is drawn on a 1000 x 1000 grid and scaled to fit, so the same code
// fills the big panel (800 px) and the tiny shelf slots (160 px).
// Returns false if the image hasn't finished loading, so the caller can try again.
function drawPanel(c, size, i, t, mode) {
  const A = animOf(i), im = IMGS[mode ? animIdx(A, t * 1000) : A.seq[0].k];
  c.save(); c.setTransform(size / 1000, 0, 0, size / 1000, 0, 0);
  c.fillStyle = BG; c.fillRect(0, 0, 1000, 1000);
  const ok = im.complete && im.naturalWidth > 0;
  if (ok) { c.imageSmoothingQuality = 'high'; c.drawImage(im, 0, 0, 1000, 1000); }
  c.restore();
  return ok;
}
