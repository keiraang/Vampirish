// ---------- 5. Clicking a finished panel: the floating words ----------
/* Click a finished panel: its words come out in reading order, hold together for a moment,
   then drift apart behind the page, bumping into walls and into each other.
   Clicking the same panel again fades its old words and sends out a fresh set in the same click.

   Each click creates a "group" (all the words of one panel). A group goes through three phases:
     'in'    each word flies from the shelf slot to its place in the line, one after another
     'hold'  the finished line sits together, bright, for 1.7 s
     'drift' the words move behind the page, dim, and wander, bouncing off walls and each other */
const groups = new Map();            // panel number -> its group of words
const bodies = [];                   // every word that is currently drifting (the ones that collide)
const HOLD = 1.7, DUR = 0.95, STAG = 0.15;   // hold time, each word's flight time, delay between words (seconds)
const REDUCED = !!(window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches);   // person asked their device for less motion
let mouse = null, hoverB = null;     // pointer position, and the word currently hovered

// Place a word on screen: position (its centre is b.x, b.y), tilt, and size.
function put(b, s = 1) {
  b.el.style.transform = `translate3d(${(b.x - b.w / 2).toFixed(1)}px,${(b.y - b.h / 2).toFixed(1)}px,0) rotate(${b.rot.toFixed(2)}deg) scale(${s})`;
}

// Pick where the assembled line should appear: try 60 random spots and keep the one that
// covers the big picture, the shelf and the poem text the least, so it stays readable.
function placeSpot(gw, gh) {
  const W = innerWidth, H = innerHeight, pad = 12;
  const avoid = [[panel, 1], [shelf, 1], [lines, .3]].map(([e, k]) => [e.getBoundingClientRect(), k]).filter(([r]) => r.width > 0);   // [thing to avoid, how much it matters]
  let best = { x: W / 2, y: H / 2 }, bo = Infinity;
  for (let k = 0; k < 60; k++) {
    const x = gw / 2 + 20 + Math.random() * Math.max(0, W - gw - 40), y = gh / 2 + 20 + Math.random() * Math.max(0, H - gh - 40);
    const L = x - gw / 2 - pad, R = x + gw / 2 + pad, T = y - gh / 2 - pad, B = y + gh / 2 + pad;
    let o = 0;   // how much this spot overlaps the things to avoid
    for (const [r, wt] of avoid) o += wt * Math.max(0, Math.min(R, r.right) - Math.max(L, r.left)) * Math.max(0, Math.min(B, r.bottom) - Math.max(T, r.top));
    if (o < bo) { bo = o; best = { x, y }; if (o === 0) break; }
  }
  return best;
}

// A shelf slot was clicked: make this panel's words.
function exude(i, slotEl) {
  if (!slots[i].on) return;
  if (groups.has(i)) removeGroup(i);                  // every click swaps this panel's old words for a fresh set
  const r = slotEl.getBoundingClientRect(), ox = r.left + r.width / 2, oy = r.top + r.height / 2, W = innerWidth;   // ox, oy = the slot's centre, where the words start
  let size = Math.max(17, Math.min(28, W * 0.0185)) * (0.92 + Math.random() * 0.16);   // font size: scales with screen width, a little random per click
  const G = { i, rows: [], all: [], phase: 'in', t0: performance.now() / 1000, ox, oy, cx: 0, cy: 0, tHold: 0 };
  // One element per word of the panel's full text (the lines before AND after the drag), kept in rows
  PANELS[i].t.concat(PANELS[i].rest || []).forEach(txt => {
    const row = txt.split(' ').map(wd => {
      const el = document.createElement('span');
      el.className = 'fw in wob'; el.textContent = wd; el.style.opacity = 0;
      fx.append(el);
      // Each word's "body": position (x,y), target spot (tx,ty), velocity (vx,vy), size (w,h), hitbox half-sizes (hw,hh), speed (s0), tilt (rot)
      const b = { el, g: G, x: ox, y: oy, tx: 0, ty: 0, vx: 0, vy: 0, w: 0, h: 0, hw: 0, hh: 0, s0: 0, rot: 0, rt: 0, t1: 0, idx: G.all.length, ph: 'in', ph0: Math.random() * TAU };
      G.all.push(b); return b;
    });
    G.rows.push(row);
  });
  /* measure each word and freeze its box, so hovering (bolder text) never changes a hitbox */
  const measure = () => {
    G.all.forEach(b => {
      const s = b.el.style; s.fontSize = size + 'px'; s.width = ''; s.height = '';
      b.w = b.el.offsetWidth + 2; b.h = b.el.offsetHeight || size;
      s.width = b.w + 'px'; s.height = b.h + 'px'; b.hw = b.w * .47; b.hh = b.h * .4;   // hitbox = 94% of the width, 80% of the height
    });
    const gap = size * .6; let gw = 0;     // typewriter-width gap between words; gw = width of the longest row
    G.rows.forEach(row => { gw = Math.max(gw, row.reduce((a, b) => a + b.w, 0) + gap * (row.length - 1)); });
    return { gap, lh: size * 1.4, gw };
  };
  let L = measure();
  if (L.gw > W - 40) { size *= (W - 40) / L.gw; L = measure(); }   // too wide for the screen: shrink to fit
  const c = placeSpot(L.gw, G.rows.length * L.lh);
  G.cx = c.x; G.cy = c.y;
  // Work out each word's resting place so the rows read as centred lines
  G.rows.forEach((row, rr) => {
    let x = -(row.reduce((a, b) => a + b.w, 0) + L.gap * (row.length - 1)) / 2;
    row.forEach(b => { b.tx = c.x + x + b.w / 2; b.ty = c.y + (rr - (G.rows.length - 1) / 2) * L.lh; x += b.w + L.gap; put(b, .3); });
  });
  groups.set(i, G);
}

// The held line lets go: move the words behind the page, dim them, and give each a push away from the line's centre.
function toDrift(G, now) {
  G.phase = 'drift';
  G.all.forEach(b => bg.append(b.el));                // move behind the page
  void bg.offsetWidth;                                // so the dimming below animates
  G.all.forEach(b => {
    b.el.classList.add('dim');
    const dx = b.x - G.cx, dy = b.y - G.cy;
    const a = Math.hypot(dx, dy) < 4 ? Math.random() * TAU : Math.atan2(dy, dx) + (Math.random() - .5) * 1.1;   // direction: outward from the centre, with some randomness
    b.s0 = (14 + Math.random() * 16) * (REDUCED ? .4 : 1);   // speed: 14-30 pixels a second (slower if reduced motion)
    b.vx = Math.cos(a) * b.s0; b.vy = Math.sin(a) * b.s0;
    b.rt = (Math.random() - .5) * 10; b.t1 = now; b.ph = 'drift';
    bodies.push(b);                                   // from now on it takes part in collisions
  });
}

// Fade a panel's words out and forget them.
function removeGroup(i) {
  const G = groups.get(i); if (!G) return;
  groups.delete(i);
  G.all.forEach(b => {
    const k = bodies.indexOf(b); if (k >= 0) bodies.splice(k, 1);
    if (hoverB === b) hoverB = null;
    b.ph = 'gone';
    b.el.classList.remove('hov', 'in'); b.el.style.opacity = '';
    b.el.classList.add('gone');                       // CSS fades it over about a second
    setTimeout(() => b.el.remove(), 1300);
  });
}
function fadeBg() { [...groups.keys()].forEach(removeGroup); }   // remove every panel's words (used by "Begin again")

// Track the mouse for the hover effect. The floating words sit behind the page, so the browser
// never tells them about the pointer; instead we remember where it is and test it ourselves.
// "blocked" = the pointer is over the picture, a shelf slot or a button, where a hidden word shouldn't react.
window.addEventListener('pointermove', e => {
  if (e.pointerType === 'touch') return;
  const t = document.elementFromPoint ? document.elementFromPoint(e.clientX, e.clientY) : null;
  mouse = { x: e.clientX, y: e.clientY, blocked: !!(t && t.closest('.panel,.slot,.again,.w,.flyer')) };
});
document.documentElement.addEventListener('mouseleave', () => { mouse = null; });

// Runs every frame: moves the words. `now` = seconds, `dt` = seconds since the last frame.
function stepWords(now, dt) {
  /* appear in order, hold, then release */
  groups.forEach(G => {
    const age = now - G.t0;
    if (G.phase === 'in') {
      G.all.forEach(b => {
        const p = c01((age - b.idx * STAG) / DUR), e = ease(p);      // p = how far along this word's flight is (0..1); later words start later
        b.x = G.ox + (b.tx - G.ox) * e; b.y = G.oy + (b.ty - G.oy) * e;
        b.el.style.opacity = c01(p * 2); put(b, .3 + .7 * e);       // fade in while growing from small to full size
      });
      if (age > (G.all.length - 1) * STAG + DUR) {                  // last word has landed
        G.phase = 'hold'; G.tHold = now;
        G.all.forEach(b => { b.x = b.tx; b.y = b.ty; b.el.classList.remove('in'); b.el.style.opacity = ''; put(b); });
      }
    } else if (G.phase === 'hold' && now - G.tHold > HOLD) toDrift(G, now);
  });

  // --- Drifting: move each word and bounce it off the screen edges ---
  const W = innerWidth, H = innerHeight;
  for (const b of bodies) {
    const m = ease((now - b.t1) / 4);                 /* start from rest and speed up gently */
    const ang = (Math.random() - .5) * 1.4 * dt, ca = Math.cos(ang), sa = Math.sin(ang);    // a tiny random turn each frame, so paths curve
    const nvx = b.vx * ca - b.vy * sa; b.vy = b.vx * sa + b.vy * ca; b.vx = nvx;
    const sp = Math.hypot(b.vx, b.vy) || 1, k = 1 + (b.s0 / sp - 1) * Math.min(1, dt * .7);  // ease the speed back toward its own target (after a bump)
    b.vx *= k; b.vy *= k;
    b.x += b.vx * dt * m; b.y += b.vy * dt * m;
    const x0 = b.w / 2 + 6, x1 = W - b.w / 2 - 6, y0 = b.h / 2 + 6, y1 = H - b.h / 2 - 6;   // the allowed area, 6 px in from each edge
    if (x0 >= x1) b.x = W / 2; else if (b.x < x0) { b.x = x0; b.vx = Math.abs(b.vx); } else if (b.x > x1) { b.x = x1; b.vx = -Math.abs(b.vx); }
    if (y0 >= y1) b.y = H / 2; else if (b.y < y0) { b.y = y0; b.vy = Math.abs(b.vy); } else if (b.y > y1) { b.y = y1; b.vy = -Math.abs(b.vy); }
    b.rot = (b.rt + Math.sin(now * .4 + b.ph0) * 1.8) * m;       // a gentle sway
  }
  /* word against word: separate along the shallow axis and trade velocity along it */
  // Compare every pair. If two hitboxes overlap, push them apart along whichever direction overlaps least,
  // and swap their speeds in that direction (like two equal balls bumping).
  for (let i = 0; i < bodies.length; i++) {
    const a = bodies[i];
    for (let j = i + 1; j < bodies.length; j++) {
      const b = bodies[j], dx = a.x - b.x, dy = a.y - b.y;
      const ox = a.hw + b.hw - Math.abs(dx), oy = a.hh + b.hh - Math.abs(dy);   // how much they overlap sideways / up-down
      if (ox <= 0 || oy <= 0) continue;                                          // not touching
      if (ox < oy) {
        const s = dx < 0 ? -1 : 1; a.x += s * ox / 2; b.x -= s * ox / 2;
        if ((a.vx - b.vx) * s < 0) { const v = a.vx; a.vx = b.vx; b.vx = v; }
      } else {
        const s = dy < 0 ? -1 : 1; a.y += s * oy / 2; b.y -= s * oy / 2;
        if ((a.vy - b.vy) * s < 0) { const v = a.vy; a.vy = b.vy; b.vy = v; }
      }
    }
  }
  /* hover: the word under the pointer turns bold and bright */
  let hit = null;
  if (mouse && !mouse.blocked && !drag) {
    let bd = 1e12;   // if several words are under the pointer, the one whose centre is nearest wins
    for (const b of bodies) {
      const dx = Math.abs(mouse.x - b.x), dy = Math.abs(mouse.y - b.y);
      if (dx <= b.w / 2 && dy <= b.h / 2 && dx * dx + dy * dy < bd) { bd = dx * dx + dy * dy; hit = b; }
    }
  }
  if (hit !== hoverB) {
    if (hoverB) hoverB.el.classList.remove('hov');
    if (hit) hit.el.classList.add('hov');             // CSS makes it bright and thick
    hoverB = hit;
  }
  for (const b of bodies) put(b);                     // finally, move every word on screen to its new position
}

// ---------- 6. The animation loop ----------
// Runs once per screen refresh (about 60 times a second). It does two jobs:
//   a) move the floating words,
//   b) show the right frame on the main panel and on each finished shelf slot.
// The pictures only change a few times a second (4 fps), so a canvas is redrawn only when its frame number changes.
let mainKey = '', lastNw = performance.now() / 1000;   // mainKey remembers "panel:frame" last drawn on the main panel
function tick(ms) {
  const nw = performance.now() / 1000; stepWords(nw, Math.min(.05, Math.max(0, nw - lastNw))); lastNw = nw;   // dt is capped so a long pause doesn't make words jump
  const t = ms / 1000;
  if (!document.hidden) {                                // don't draw while the tab is hidden
    if (mode !== 'over') {                             /* redraw only when the picture changes */
      const A = animOf(cur), story = mode === 'story', ts = story ? t - storyT0 : t;   // ts = seconds into the story
      const k = cur + ':' + (story ? animIdx(A, ts * 1000) : A.seq[0].k);
      if (k !== mainKey && drawPanel(sc, 800, cur, ts, story ? 1 : 0)) mainKey = k;
    }
    // Finished shelf slots loop their animation forever. Each is offset by 0.43 s per slot so they don't all move in sync.
    slots.forEach((s, i) => {
      if (!s.on) return;
      const ts = t + i * .43, k = animIdx(animOf(i), ts * 1000);
      if (k !== s.k && drawPanel(s.c, 160, i, ts, 1)) s.k = k;
    });
  }
  requestAnimationFrame(tick);
}
