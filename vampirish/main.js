// ---------- 3. Dragging a word ----------
// Pressing on a word: hide the original and make a floating copy ("ghost") that follows the pointer.
// Pointer events cover mouse, finger and pen with the same code.
lines.addEventListener('pointerdown', e => {
  const w = e.target.closest('.w');
  if (!w || mode !== 'idle' || drag) return;              // only words, only while waiting, only one at a time
  e.preventDefault();
  const r = w.getBoundingClientRect(), cs = getComputedStyle(w);
  const g = document.createElement('div');
  g.className = 'ghost wob'; g.textContent = w.textContent;
  Object.assign(g.style, { left: r.left + 'px', top: r.top + 'px', fontSize: cs.fontSize, transform: tf(0, 0) });
  document.body.append(g); w.classList.add('lifted');
  drag = { w, g, id: e.pointerId, sx: e.clientX, sy: e.clientY, dx: 0, dy: 0, hot: false };
});
// Moving: slide the ghost, and check whether it is over the picture ("hot", with a 20 px margin).
window.addEventListener('pointermove', e => {
  if (!drag || e.pointerId !== drag.id) return;
  drag.dx = e.clientX - drag.sx; drag.dy = e.clientY - drag.sy;
  drag.g.style.transform = tf(drag.dx, drag.dy);
  const gr = drag.g.getBoundingClientRect(), pr = panel.getBoundingClientRect();
  const x = gr.left + gr.width / 2, y = gr.top + gr.height / 2;
  drag.hot = x > pr.left - 20 && x < pr.right + 20 && y > pr.top - 20 && y < pr.bottom + 20;
  panel.classList.toggle('hot', drag.hot);                // red glow around the picture
});
// Letting go: over the picture = check the answer; anywhere else = the word goes home.
const endDrag = e => {
  if (!drag || e.pointerId !== drag.id) return;
  const d = drag; drag = null; panel.classList.remove('hot');
  if (d.hot && e.type === 'pointerup') attempt(d); else goHome(d);
};
window.addEventListener('pointerup', endDrag);
window.addEventListener('pointercancel', endDrag);
// Keyboard alternative: focus a word and press Enter or Space to "drop" it.
lines.addEventListener('keydown', e => {
  const w = e.target.closest('.w');
  if (!w || mode !== 'idle' || (e.key !== 'Enter' && e.key !== ' ')) return;
  e.preventDefault(); attempt({ w, g: null, dx: 0, dy: 0 });
});

// ---------- 4. Right or wrong, the story, and moving on ----------
// Is the dropped word the keyword for this panel?
function attempt(d) { norm(d.w.textContent) === norm(PANELS[cur].key) ? success(d) : wrong(d); }

// The ghost slides back to where the word came from.
function goHome(d) {
  d.g.animate([{ transform: tf(d.dx, d.dy) }, { transform: tf(0, 0, 1) }], { duration: 320, easing: 'cubic-bezier(.3,1.3,.5,1)', fill: 'forwards' })
    .onfinish = () => { d.g.remove(); d.w.classList.remove('lifted'); };
}

// Wrong word: shake, then go home. After two misses the right word glows as a hint.
function wrong(d) {
  misses++;
  if (misses >= 2) lines.querySelectorAll('.w').forEach(x => { if (norm(x.textContent) === norm(PANELS[cur].key)) x.classList.add('hint'); });
  const el = d.g || d.w;
  const a = el.animate([{ translate: '0 0' }, { translate: '-12px 0' }, { translate: '12px 0' }, { translate: '-8px 0' }, { translate: '0 0' }], { duration: 360 });
  a.onfinish = () => { if (d.g) goHome(d); };
}

// Right word: start the story.
function success(d) {
  mode = 'story'; storyT0 = performance.now() / 1000;    // the drawing loop (section 6) now plays the animation from this moment
  lines.classList.add('done');
  lines.querySelectorAll('.w').forEach(x => { x.classList.remove('lifted', 'hint'); x.removeAttribute('tabindex'); });
  d.w.classList.add('key');                               // the keyword turns red
  // Reveal the rest of the line, each word fading in a beat after the last (the --k number drives the delay in CSS)
  const rest = PANELS[cur].rest;
  if (rest) rest.forEach(txt => {
    const ln = document.createElement('div'); ln.className = 'line rest';
    txt.split(' ').forEach((wd, k) => {
      const s = document.createElement('span'); s.className = 'w'; s.textContent = wd; s.style.setProperty('--k', k);
      ln.append(s, ' ');
    });
    lines.append(ln);
  });
  note.style.opacity = 0;
  panel.classList.remove('flash'); void panel.offsetWidth; panel.classList.add('flash');   // white ripple around the picture (the "void" line restarts the CSS animation)
  // The ghost word shrinks into the middle of the picture and disappears
  if (d.g) {
    const pr = panel.getBoundingClientRect(), gr = d.g.getBoundingClientRect();
    const ex = pr.left + pr.width / 2 - (gr.left + gr.width / 2), ey = pr.top + pr.height / 2 - (gr.top + gr.height / 2);
    d.g.animate([{ transform: tf(d.dx, d.dy), opacity: 1 }, { transform: tf(d.dx + ex, d.dy + ey, .15), opacity: 0 }], { duration: 420, easing: 'ease-in', fill: 'forwards' })
      .onfinish = () => d.g.remove();
  }
  // Let the story play for at least 4.8 s (or the animation's length + 2.2 s if that's longer), then move on
  const A = animOf(cur);
  setTimeout(toShelf, Math.max(4800, A ? A.total + 2200 : 0));
}

// Send the finished picture up to its slot on the shelf, then show the next panel.
function toShelf() {
  if (mode !== 'story') return;
  const i = cur, pr = panel.getBoundingClientRect(), sr = slots[i].b.getBoundingClientRect();
  // Copy the current picture into a "flyer" and fly it from the panel to the slot (850 ms)
  const fl = document.createElement('div'); fl.className = 'flyer';
  const cp = document.createElement('canvas'); cp.width = cp.height = 400;
  cp.getContext('2d').drawImage(cv, 0, 0, 400, 400); fl.append(cp);
  Object.assign(fl.style, { left: pr.left + 'px', top: pr.top + 'px', width: pr.width + 'px', height: pr.height + 'px', transformOrigin: '0 0' });
  document.body.append(fl);
  fl.animate([{ transform: 'translate(0,0) scale(1)' }, { transform: `translate(${sr.left - pr.left}px,${sr.top - pr.top}px) scale(${sr.width / pr.width})` }],
    { duration: 850, easing: 'cubic-bezier(.65,0,.25,1)', fill: 'forwards' })
    .onfinish = () => { slots[i].on = true; slots[i].k = -1; slots[i].b.classList.add('filled'); slots[i].b.disabled = false; fl.remove(); };   // when it lands, the slot becomes live
  doneN++; cnt.textContent = doneN;
  if (i < N - 1) loadPanel(i + 1); else finale();
}

